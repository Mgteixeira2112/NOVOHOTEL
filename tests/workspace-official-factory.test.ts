import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { workspaceRegistry } from '../src/workspace-engine/registry';
import { createWorkspaceDefinition } from '../src/workspace-engine/workspaceFactory';
import { createOfficialWorkspaceDefinition, OFFICIAL_WORKSPACE_TEMPLATES } from '../src/workspace-engine/workspaceOfficialFactory';

test('official operational instances are generated by the Workspace Factory', () => {
  assert.deepEqual(
    workspaceRegistry,
    OFFICIAL_WORKSPACE_TEMPLATES.map(template => createOfficialWorkspaceDefinition(template.id)),
  );
  assert.deepEqual(workspaceRegistry.map(item => item.id), [
    'workspace-governanca',
    'workspace-recepcao',
    'workspace-operacao',
    'workspace-manutencao',
    'workspace-cozinha',
  ]);
});

test('factory cutover preserves historical base ids and widget ids', () => {
  const governance = createOfficialWorkspaceDefinition('workspace-governanca');
  const reception = createOfficialWorkspaceDefinition('workspace-recepcao');

  assert.equal(governance.widgets.some(widget => widget.id === 'governanca-kanban'), true);
  assert.equal(reception.widgets.some(widget => widget.id === 'recepcao-reservas'), true);
  assert.equal(reception.widgets.some(widget => widget.id === 'recepcao-calendario-ocupacao'), true);
  assert.equal(reception.widgets.some(widget => widget.id === 'recepcao-kanban'), true);
});

test('new official sectors reuse the existing sector compositions', () => {
  const cases = [
    { id: 'workspace-operacao' as const, name: 'Operação Geral', sector: 'operacao' as const },
    { id: 'workspace-manutencao' as const, name: 'Manutenção', sector: 'manutencao' as const },
    { id: 'workspace-cozinha' as const, name: 'Cozinha & Room Service', sector: 'cozinha' as const },
  ];

  for (const item of cases) {
    assert.deepEqual(
      createOfficialWorkspaceDefinition(item.id).widgets,
      createWorkspaceDefinition(item).widgets,
    );
  }
});

test('registry no longer declares official Workspace objects by hand', () => {
  const source = readFileSync(new URL('../src/workspace-engine/registry.ts', import.meta.url), 'utf8');
  assert.match(source, /createOfficialWorkspaceDefinitions\(\)/);
  assert.doesNotMatch(source, /id:\s*['"]workspace-governanca['"]/);
  assert.doesNotMatch(source, /id:\s*['"]workspace-recepcao['"]/);
  assert.doesNotMatch(source, /id:\s*['"]workspace-operacao['"]/);
  assert.doesNotMatch(source, /id:\s*['"]workspace-manutencao['"]/);
  assert.doesNotMatch(source, /id:\s*['"]workspace-cozinha['"]/);
  assert.doesNotMatch(source, /widgets:\s*normalizeWorkspaceWidgets/);
});
